#!/usr/bin/env python3
"""Generate src/memory_package.vhd from the binaries produced by sw/Makefile.

The instruction memory and the data ROM are VHDL constants, so every program
is "loaded" by regenerating this package before simulation or synthesis.
"""
import argparse
from pathlib import Path

DATA_MEMORY_BASE = 0x00FC8000   # data ROM base (must match sw/linker.ld)
DATA_ROM_BYTES = 256            # ROM size in the memory map (RAM starts right after)
DATA_RAM_BYTES = 512


def words(data: bytes, min_words: int):
    if len(data) % 4:
        data += bytes(4 - len(data) % 4)
    data += bytes(max(0, 4 * min_words - len(data)))
    return [data[i:i + 4] for i in range(0, len(data), 4)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--instr", required=True, type=Path)
    ap.add_argument("--rodata", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    a = ap.parse_args()

    instr = words(a.instr.read_bytes(), 2)        # at least 2 instructions
    rodata = words(a.rodata.read_bytes(), 2)      # at least 8 bytes
    if 4 * len(rodata) > DATA_ROM_BYTES:
        raise SystemExit(f"rodata+data ({4*len(rodata)} B) exceeds the {DATA_ROM_BYTES} B data ROM")

    instr_lines = ",\n".join(f'            x"{int.from_bytes(w, "little"):08x}"' for w in instr)
    rom_lines = ",\n".join(
        "            (" + ", ".join(f'x"{b:02x}"' for b in reversed(w)) + ")" for w in rodata)

    a.out.write_text(f"""-- Project      : PIPELINED_RISC-V_RV32I
-- Author       : Omar Othmeni <https://github.com/OmarOthmeni>
-- File         : memory_package.vhd
-- Description  : GENERATED by scripts/gen_memory_package.py from {a.instr.name} / {a.rodata.name}.
--                Do not edit by hand: rebuild with `make -C sw PROG=...`.

library IEEE;
use IEEE.STD_LOGIC_1164.ALL;

package memory_package is

    type MEMORY_ACCESS_WIDTH_t is (MEMORY_ACCESS_WIDTH_BYTE, MEMORY_ACCESS_WIDTH_HALFWORD, MEMORY_ACCESS_WIDTH_WORD);
    type MEMORY_ACCESS_TYPE_t  is (MEMORY_ACCESS_TYPE_READ, MEMORY_ACCESS_TYPE_WRITE);

    constant DATA_MEMORY_BASE_ADDRESS : integer := 16#{DATA_MEMORY_BASE:08X}#;

    ------------------------------------------------------------------ Instruction memory
    constant RESET_HANDLER_ADDRESS          : integer := 16#00000000#;
    constant INSTRUCTION_MEMORY_SIZE_BYTES  : integer := {4*len(instr)};
    constant INSTRUCTION_MEMORY_SIZE_WORDS  : integer := INSTRUCTION_MEMORY_SIZE_BYTES/4;

    type INSTRUCTION_MEMORY_ARRAY_t is array(0 to INSTRUCTION_MEMORY_SIZE_WORDS-1) of std_logic_vector(31 downto 0);

    constant INSTRUCTION_MEMORY_CONTENT : INSTRUCTION_MEMORY_ARRAY_t := (
{instr_lines}
        );

    ------------------------------------------------------------------ Data ROM
    constant DATA_ROM_MEMORY_SIZE_BYTES     : integer := {4*len(rodata)};
    constant DATA_ROM_MEMORY_SIZE_WORDS     : integer := DATA_ROM_MEMORY_SIZE_BYTES/4;

    type DATA_ROM_MEMORY_ARRAY_t is array (0 to DATA_ROM_MEMORY_SIZE_WORDS-1, 3 downto 0) of std_logic_vector(7 downto 0);

    constant DATA_ROM_MEMORY_CONTENT : DATA_ROM_MEMORY_ARRAY_t := (
{rom_lines}
        );

    ------------------------------------------------------------------ Data RAM
    constant DATA_RAM_BASE_ADDRESS        : integer := 16#{DATA_MEMORY_BASE + DATA_ROM_BYTES:08X}#;
    constant DATA_RAM_MEMORY_SIZE_BYTES   : integer := {DATA_RAM_BYTES};
    constant DATA_RAM_MEMORY_SIZE_WORDS   : integer := DATA_RAM_MEMORY_SIZE_BYTES/4;

    type DATA_RAM_MEMORY_ARRAY_t is array (0 to DATA_RAM_MEMORY_SIZE_WORDS-1, 3 downto 0) of std_logic_vector(7 downto 0);

end package memory_package;
""")
    print(f"{a.out}: {4*len(instr)} B instructions, {4*len(rodata)} B data ROM")


if __name__ == "__main__":
    main()
